#!/usr/bin/env python3
"""Build and host the C3-C documentation site.

Outputs:
- ``docs/data-dictionary.md`` from the registry and live schemas;
- ``docs/_site/`` (dbt docs + a static GX Data Docs renderer);
- an optional upload of both trees to ``s3://docs``;
- ``evidence/deploy/docs-hosting_<ts>.json`` with HTTP and S3 checks.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import shutil
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import httpx
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "docs" / "_site"
EVIDENCE = ROOT / "evidence" / "deploy"
DOCS_URL = "http://127.0.0.1:8089"
load_dotenv(ROOT / ".env")


def _stamp() -> str:
    return datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")


def _sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return os.getenv("BMIP_COMMIT", "nogit")


def _api_schema(dataset_id: str) -> list[dict[str, Any]]:
    base = os.getenv("BMIP_API_BASE_URL", "http://127.0.0.1:8000").rstrip("/")
    headers = {}
    key = os.getenv("BMIP_API_KEY", "")
    if key:
        headers["X-API-Key"] = key
    try:
        response = httpx.get(
            f"{base}/v1/dataset/{dataset_id}/schema", headers=headers, timeout=8
        )
        if response.status_code == 200:
            return response.json().get("columns") or []
    except httpx.HTTPError:
        pass
    return []


def _db_schemas() -> dict[str, list[dict[str, Any]]]:
    try:
        import psycopg
        from psycopg.rows import dict_row

        from bmip.common.config import get_settings

        with psycopg.connect(
            get_settings().postgres_dsn, connect_timeout=3, row_factory=dict_row
        ) as connection:
            rows = connection.execute(
                "SELECT id, schema_json FROM serving.catalog_datasets"
            ).fetchall()
        return {row["id"]: row["schema_json"] or [] for row in rows}
    except Exception:  # noqa: BLE001 - docs must still build offline
        return {}


def _data_dictionary() -> tuple[str, list[dict[str, Any]]]:
    from bmip.serving.registry import load_registry

    datasets = sorted(load_registry(), key=lambda item: item.id)
    db_schemas = _db_schemas()
    lines = [
        "# Data Dictionary - BMIP",
        "",
        "Generated by `make docs` (`scripts/c3c_docs.py`) from "
        "`ops.dataset_registry` and the live schemas. Do not edit by hand.",
        "",
        f"- Generated: {datetime.now(UTC).date().isoformat()}",
        f"- Datasets: {len(datasets)}",
        "",
        "| Dataset | Layer | Owner | Classification | Retention | Status |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    payload: list[dict[str, Any]] = []
    for dataset in datasets:
        lines.append(
            f"| `{dataset.id}` | {dataset.layer} | {dataset.owner} | "
            f"{dataset.classification} | {dataset.retention_days} days | "
            f"{dataset.status or 'active'} |"
        )
        columns = _api_schema(dataset.id) or db_schemas.get(dataset.id) or []
        payload.append(
            {
                "id": dataset.id,
                "name": dataset.name,
                "description": dataset.description,
                "owner": dataset.owner,
                "layer": dataset.layer,
                "domain": dataset.domain,
                "classification": dataset.classification,
                "retention_days": dataset.retention_days,
                "refresh_schedule": dataset.refresh_schedule,
                "status": dataset.status or "active",
                "columns": columns,
            }
        )
    lines.append("")
    for item in payload:
        lines += [
            f"## {item['id']}",
            "",
            item["description"] or "-",
            "",
            f"- Owner: {item['owner']}",
            f"- Layer/domain: {item['layer']} / {item['domain']}",
            f"- Classification: {item['classification']}",
            f"- Retention: {item['retention_days']} days",
            f"- Refresh: {item['refresh_schedule'] or '-'}",
            f"- Status: {item['status']}",
            "",
        ]
        if item["columns"]:
            lines += [
                "| Column | Type | Required | Description |",
                "| --- | --- | --- | --- |",
            ]
            for column in item["columns"]:
                lines.append(
                    f"| `{column.get('name')}` | {column.get('type')} | "
                    f"{column.get('required', True)} | {column.get('doc') or '-'} |"
                )
        else:
            lines.append("_Schema not available in this run._")
        lines.append("")
    return "\n".join(lines) + "\n", payload


def _write_site(dictionary: list[dict[str, Any]]) -> None:
    SITE.mkdir(parents=True, exist_ok=True)
    rows = []
    for item in dictionary:
        columns = ", ".join(
            f"{column.get('name')} {column.get('type')}" for column in item["columns"]
        )
        rows.append(
            "<tr>"
            f"<td><code>{html.escape(item['id'])}</code></td>"
            f"<td>{html.escape(item['layer'])}</td>"
            f"<td>{html.escape(item['owner'])}</td>"
            f"<td>{html.escape(item['classification'])}</td>"
            f"<td>{item['retention_days']}</td>"
            f"<td>{html.escape(item['status'])}</td>"
            f"<td><code>{html.escape(columns) if columns else '-'}</code></td>"
            "</tr>"
        )
    index = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>BMIP docs</title>
<style>body{{font-family:system-ui,sans-serif;margin:2rem;max-width:1200px}}
table{{border-collapse:collapse;width:100%}}
td,th{{border:1px solid #ccc;padding:.35rem;text-align:left}}
code{{font-size:.85em}}</style></head><body>
<h1>BMIP documentation</h1>
<ul>
<li><a href="/dbt/index.html">dbt docs</a></li>
<li><a href="/gx/">GX Data Docs</a></li>
<li><a href="/data-dictionary.md">Data dictionary (Markdown)</a></li>
</ul>
<h2>Datasets</h2>
<table><thead><tr><th>Dataset</th><th>Layer</th><th>Owner</th><th>Classification</th>
<th>Retention</th><th>Status</th><th>Columns</th></tr></thead><tbody>
{''.join(rows)}
</tbody></table>
</body></html>
"""
    (SITE / "index.html").write_text(index, encoding="utf-8")
    shutil.copyfile(ROOT / "docs" / "data-dictionary.md", SITE / "data-dictionary.md")
    _write_gx()


def _write_gx() -> None:
    gx_dir = SITE / "gx"
    gx_dir.mkdir(parents=True, exist_ok=True)
    report_path = ROOT / "evidence" / "dq" / "dq_report.json"
    if not report_path.is_file():
        (gx_dir / "index.html").write_text(
            "<!doctype html><h1>GX Data Docs</h1><p>No dq_report.json found.</p>",
            encoding="utf-8",
        )
        return
    report = json.loads(report_path.read_text(encoding="utf-8"))
    suites = []
    for suite in report.get("suites", []):
        rules = "".join(
            "<tr>"
            f"<td>{html.escape(str(rule.get('id')))}</td>"
            f"<td>{html.escape(str(rule.get('severity')))}</td>"
            f"<td>{html.escape(str(rule.get('status')))}</td>"
            f"<td><code>{html.escape(json.dumps(rule.get('observed'), default=str))}</code></td>"
            f"<td>{html.escape(str(rule.get('detail') or ''))}</td>"
            "</tr>"
            for rule in suite.get("rules", [])
        )
        suites.append(
            f"<h2>{html.escape(str(suite.get('suite')))} "
            f"<small>({html.escape(str(suite.get('status')))}, "
            f"{suite.get('rows')} rows)</small></h2>"
            f"<table><thead><tr><th>Rule</th><th>Severity</th><th>Status</th>"
            f"<th>Observed</th><th>Detail</th></tr></thead><tbody>{rules}</tbody></table>"
        )
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>GX Data Docs - BMIP</title>
<style>body{{font-family:system-ui,sans-serif;margin:2rem}}
table{{border-collapse:collapse;width:100%;margin-bottom:1.5rem}}
td,th{{border:1px solid #ccc;padding:.3rem;text-align:left}}code{{font-size:.8em}}</style>
</head><body>
<h1>GX Data Docs</h1>
<p>Static renderer for <code>evidence/dq/dq_report.json</code>. The report is the
same one used by the gold gate; this page exists because GX 1.x Data Docs needs a
configured context and the project keeps the checkpoint deterministic.</p>
<p>Status: <strong>{html.escape(str(report.get('status')))}</strong> -
critical failures: {len(report.get('critical_failures') or [])},
warnings: {len(report.get('warning_failures') or [])},
generated at {html.escape(str(report.get('generated_at')))}.</p>
{''.join(suites)}
</body></html>
"""
    (gx_dir / "index.html").write_text(page, encoding="utf-8")


def _dbt_docs() -> dict[str, Any]:
    target = ROOT / "dbt" / "target"
    dbt = shutil.which("dbt") or str(Path(sys.executable).with_name("dbt.exe"))
    command = [
        dbt,
        "docs",
        "generate",
        "--project-dir",
        str(ROOT / "dbt"),
        "--profiles-dir",
        str(ROOT / "dbt"),
    ]
    try:
        result = subprocess.run(
            command,
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=900,
            check=False,
            env={
                **os.environ,
                "DBT_DUCKDB_PATH": str(ROOT / "dbt" / "target" / "bmip.duckdb"),
                "DBT_PROFILES_DIR": str(ROOT / "dbt"),
            },
        )
        returncode = result.returncode
        output = (result.stderr or result.stdout or "")[-600:]
    except subprocess.TimeoutExpired:
        returncode = 124
        output = "dbt docs generate exceeded 900s; copied the existing target"
    dbt_dir = SITE / "dbt"
    dbt_dir.mkdir(parents=True, exist_ok=True)
    copied: list[str] = []
    for name in ("index.html", "manifest.json", "catalog.json", "graph_summary.json"):
        source = target / name
        if source.is_file():
            shutil.copyfile(source, dbt_dir / name)
            copied.append(name)
    return {
        "returncode": returncode,
        "target": str(target.relative_to(ROOT)),
        "copied": copied,
        "stderr_tail": output,
    }


def _upload() -> list[str]:
    try:
        import boto3
        from botocore.config import Config
    except ImportError:
        return []
    endpoint = os.getenv("MINIO_ENDPOINT", "http://127.0.0.1:9000")
    key = os.getenv("MINIO_SVC_DOCS_ACCESS_KEY", "svc-docs")
    secret = os.getenv("MINIO_SVC_DOCS_SECRET_KEY", "")
    if not secret:
        return []
    client = boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=key,
        aws_secret_access_key=secret,
        region_name=os.getenv("MINIO_S3_REGION", "local"),
        config=Config(s3={"addressing_style": "path"}),
    )
    uploaded: list[str] = []
    for path in sorted(SITE.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(SITE).as_posix()
        client.upload_file(str(path), "docs", relative)
        uploaded.append(f"s3://docs/{relative}")
    return uploaded


def _serve() -> str:
    try:
        response = httpx.get(f"{DOCS_URL}/", timeout=3)
        if response.status_code == 200:
            return ""
    except httpx.HTTPError:
        pass
    command = [
        "docker",
        "compose",
        "--env-file",
        str(ROOT / ".env"),
        "-f",
        str(ROOT / "deploy" / "compose.base.yml"),
        "-f",
        str(ROOT / "deploy" / "compose.dev.yml"),
        "--profile",
        "n1",
        "--profile",
        "n2",
        "--profile",
        "n3",
        "--profile",
        "n4",
        "--profile",
        "docs",
        "up",
        "-d",
        "docs",
    ]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        return (result.stderr or result.stdout)[:600]
    for _ in range(30):
        try:
            response = httpx.get(f"{DOCS_URL}/", timeout=3)
            if response.status_code == 200:
                return ""
        except httpx.HTTPError:
            pass
        __import__("time").sleep(1)
    return "docs service did not become ready"


def _screenshot(path: Path) -> str | None:
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        return None
    try:
        with sync_playwright() as playwright:
            browser = playwright.chromium.launch()
            page = browser.new_page(viewport={"width": 1440, "height": 1000})
            page.goto(f"{DOCS_URL}/", wait_until="networkidle", timeout=60000)
            page.wait_for_timeout(1500)
            page.screenshot(path=str(path), full_page=True)
            browser.close()
        return str(path.relative_to(ROOT))
    except Exception as exc:  # noqa: BLE001
        print(f"screenshot failed: {exc}", file=sys.stderr)
        return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serve", action="store_true", help="start the docs service and check it")
    parser.add_argument("--upload", action="store_true", help="upload the site to s3://docs")
    parser.add_argument(
        "--skip-dbt",
        action="store_true",
        help="copy the existing dbt target instead of running dbt docs generate",
    )
    args = parser.parse_args(argv)

    EVIDENCE.mkdir(parents=True, exist_ok=True)
    markdown, dictionary = _data_dictionary()
    (ROOT / "docs" / "data-dictionary.md").write_text(markdown, encoding="utf-8")
    _write_site(dictionary)
    dbt = (
        {"returncode": 0, "target": "dbt/target", "copied": [], "stderr_tail": "skipped"}
        if args.skip_dbt
        else _dbt_docs()
    )
    if args.skip_dbt:
        dbt_dir = SITE / "dbt"
        dbt_dir.mkdir(parents=True, exist_ok=True)
        for name in ("index.html", "manifest.json", "catalog.json", "graph_summary.json"):
            source = ROOT / "dbt" / "target" / name
            if source.is_file():
                shutil.copyfile(source, dbt_dir / name)
                dbt["copied"].append(name)
    uploaded = _upload() if args.upload else []
    serve_error = _serve() if args.serve else ""

    http_checks: dict[str, Any] = {}
    for path in ("/", "/gx/", "/dbt/"):
        try:
            response = httpx.get(f"{DOCS_URL}{path}", timeout=8)
            http_checks[path] = {"status": response.status_code, "ok": response.status_code == 200}
        except httpx.HTTPError as exc:
            http_checks[path] = {"status": 0, "ok": False, "error": str(exc)}

    stamp = _stamp()
    screenshot = _screenshot(EVIDENCE / f"docs-hosting_{stamp}.png") if args.serve else None
    passed = (
        (not args.serve or all(check["ok"] for check in http_checks.values()))
        and (
            dbt["returncode"] == 0
            or {"index.html", "manifest.json", "catalog.json"}.issubset(set(dbt["copied"]))
        )
        and len(dictionary) >= 11
    )
    document = {
        "id": "CP3-docs-hosting",
        "timestamp": datetime.now(UTC).isoformat(),
        "commit": _sha(),
        "command": "python scripts/c3c_docs.py --serve --upload",
        "result": "PASS" if passed else "FAIL",
        "owner": "vio",
        "datasets": len(dictionary),
        "dbt": dbt,
        "uploaded": uploaded,
        "serve_error": serve_error,
        "http": http_checks,
        "screenshot": screenshot,
        "data_dictionary": "docs/data-dictionary.md",
        "site": "docs/_site",
    }
    path = EVIDENCE / f"docs-hosting_{stamp}.json"
    path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({**document, "evidence": str(path.relative_to(ROOT))}, indent=2))
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
